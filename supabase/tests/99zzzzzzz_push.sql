-- Phone push: each person saves and sees only their own phones; a token moves to whoever signed in last; a notification still saves without pg_net.
begin;
select tests.fixture();
select tests.login(tests.id('hub_mgr'));
select public.push_device_save('tok-aaaaaaaaaaaaaaaaaaaaaaaaaaaa', 'android', '1.80');
select tests.ok((select count(*) = 1 from public.push_devices), 'the hub manager saved a phone');
select tests.throws($$select public.push_device_save('short')$$, 'a short token is refused', '22023');
select tests.throws($$insert into public.push_devices (profile_id, token) values (auth.uid(), 'tok-bbbbbbbbbbbbbbbbbbbbbbbbbbbbbb')$$, 'no direct writes', '42501');
select tests.logout();
select tests.login(tests.id('zonal_a'));
select tests.ok((select count(*) = 0 from public.push_devices), 'another person does not see it');
select public.push_device_save('tok-aaaaaaaaaaaaaaaaaaaaaaaaaaaa');
select tests.ok((select count(*) = 1 from public.push_devices), 'the same phone signed in by someone else moves to them');
select public.push_device_remove('tok-aaaaaaaaaaaaaaaaaaaaaaaaaaaa');
select tests.ok((select disabled_at is not null from public.push_devices), 'signing out switches the phone off');
select tests.logout();
select tests.login_anon();
select tests.throws($$select public.push_device_save('tok-cccccccccccccccccccccccccccc')$$, 'anon cannot save', '42501');
select tests.logout();
insert into public.notifications (profile_id, title) values (tests.id('zonal_a'), 'test');
select tests.ok((select pushed_at is null from public.notifications where title = 'test'), 'a new notification waits unsent and saves fine');
select public.push_device_save('x') where false;
update public.push_devices set disabled_at = null;
select tests.ok((select count(*) = 1 and bool_and(array_length(tokens, 1) = 1) from public.push_claim(50) where title = 'test'), 'the sender takes the waiting row with the phone''s token');
select tests.ok((select count(*) = 0 from public.push_claim(50)), 'a second run takes nothing — no row is sent twice');
select public.push_device_dead(array['tok-aaaaaaaaaaaaaaaaaaaaaaaaaaaa']);
select tests.ok((select disabled_at is not null from public.push_devices), 'a dead token is switched off');
select tests.login(tests.id('zonal_a'));
select tests.throws($$select * from public.push_claim(1)$$, 'a person cannot take the queue', '42501');
select tests.logout();
rollback;
