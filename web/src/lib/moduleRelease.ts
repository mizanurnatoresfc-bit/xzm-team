export type ReleaseStage = 'planning' | 'development' | 'testing' | 'ready' | 'published' | 'maintenance' | 'disabled'
export type ModuleRelease = { id: string; stage: ReleaseStage; roles: readonly string[]; hubs: readonly string[]; platforms: readonly ('web' | 'android')[] }
// Pure policy helper for future integration. Existing permissions must be evaluated independently.
export function releaseAllows(release: ModuleRelease, context: { role: string; hub: string; platform: 'web' | 'android'; permitted: boolean }): boolean {
  return context.permitted && release.stage === 'published' && release.roles.includes(context.role) && release.hubs.includes(context.hub) && release.platforms.includes(context.platform)
}
