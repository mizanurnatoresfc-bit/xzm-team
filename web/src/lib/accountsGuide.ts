// ---- automatic sorting of an expense: the same rule the sheet itself uses when saving ----
// Staff ID given → "employee" (স্টাফ খরচ); none → "transport" (যাতায়াত ও হাবের খরচ). No bill/voucher file → also "ভাউচার জমা হয়নি".
export const TRANSPORT_CATEGORIES = ['transport', 'conveyance', 'toll']
export type ExpenseSort = { kind: 'employee' | 'transport'; missingVoucher: boolean; label: string }
export function sortExpense(e: { staffId?: string | null; hasVoucherFile: boolean }): ExpenseSort {
  const kind = (e.staffId ?? '').trim() ? 'employee' : 'transport'
  const name = kind === 'employee' ? 'স্টাফ খরচ' : 'যাতায়াত ও হাবের খরচ'
  return { kind, missingVoucher: !e.hasVoucherFile, label: e.hasVoucherFile ? name : `${name} · ভাউচার জমা হয়নি` }
}

/** MATCH / NOT MATCH / NEEDS REVIEW — the same rule as the database (private.da_slip_match). */
export function slipMatch(amount: number, ocr: number | null, confidence: number | null, minConfidence = 60): 'match' | 'not_match' | 'review' {
  if (ocr === null || ocr === undefined || Number.isNaN(ocr)) return 'review'
  if ((confidence ?? 0) < minConfidence) return 'review'
  return Math.abs(amount - ocr) < 1 ? 'match' : 'not_match'
}
