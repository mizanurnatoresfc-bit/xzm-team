"""Builds supabase/migrations/20261119040000_route_places.sql: Natore district's upazilas, villages, markets and unions.

Sources (read from the unpacked npm packages, versions pinned below; nothing is fetched by this script):
  * bd-geo-info@5.3.0        dist/esm/data/bd-places.json  (GeoNames villages, CC BY 4.0), unions.json, bd-upazilas.json
  * bangladesh-geojson@1.0.0 src/data/bangladesh.geojson   (geoBoundaries ADM3 2020, CC BY 4.0), bd-bazars.geojson (© OpenStreetMap contributors, ODbL)
Usage:  npm pack bd-geo-info@5.3.0 bangladesh-geojson@1.0.0 (each in its own empty folder, then tar xzf)
        python3 -I scripts/route-places/build.py <folder with bd-geo-info/package and bangladesh-geojson/package> > supabase/migrations/...sql
"""
import json, re, sys

ROOT = sys.argv[1]
B = ROOT + '/bd-geo-info/package/dist/esm/data/'
G = ROOT + '/bangladesh-geojson/package/src/data/'
# upazila code = the bd-geo-info / BBS-style id used by bangladesh-geocode
UPZ = {143: ('Natore Sadar', 'নাটোর সদর'), 144: ('Singra', 'সিংড়া'), 145: ('Baraigram', 'বড়াইগ্রাম'), 146: ('Bagatipara', 'বাগাতিপাড়া'),
       147: ('Lalpur', 'লালপুর'), 148: ('Gurudaspur', 'গুরুদাসপুর'), 149: ('Naldanga', 'নলডাঙ্গা')}
BY_NAME = {v[0]: k for k, v in UPZ.items()}

def q(s):
    return 'null' if s is None else "'" + str(s).replace("'", "''") + "'"

def num(x):
    return 'null' if x is None else f'{x:.7f}'

gj = json.load(open(G + 'bangladesh.geojson'))
polys = {}
for f in gj['features']:
    p = f['properties']
    if p['name'] in BY_NAME and p.get('district_name') in ('Natore', ''):
        g = f['geometry']
        rings = g['coordinates'] if g['type'] == 'Polygon' else [pp[0] for pp in g['coordinates']]
        polys[BY_NAME[p['name']]] = max(rings, key=len)  # outer ring of the largest part

def inside(lng, lat, ring):
    ins, j = False, len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]; xj, yj = ring[j][0], ring[j][1]
        if (yi > lat) != (yj > lat) and lng < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            ins = not ins
        j = i
    return ins

def upazila_of(lat, lng, own=None):
    hit = [u for u, r in polys.items() if inside(lng, lat, r)]
    if own in UPZ and (not hit or own in hit or (own == 149 and 143 in hit)):
        return own            # Naldanga was cut out of Natore Sadar after the 2020 boundaries: keep the source's choice
    return hit[0] if hit else None

rows = []   # (upazila, kind, name, name_bn, bn_checked, lat, lng, source, ref)
seen = set()
places = json.load(open(B + 'bd-places.json'))
KIND = {'VILLAGE': 'village', 'TOWN': 'town', 'MARKET': 'market', 'AREA': 'para'}
for uid, lst in places['byUpazila'].items():
    for name, bn, kind, lat, lng in lst:
        u = upazila_of(lat, lng, int(uid))
        if u is None:
            continue
        ref = f'{name}@{lat:.4f},{lng:.4f}'
        if ref in seen:
            continue
        seen.add(ref)
        rows.append((u, KIND.get(kind, 'other'), name, bn or None, False, lat, lng, 'geonames', ref))

BN = re.compile(r'[ঀ-৿]')
MKT = re.compile(r'bazar|bazaar|\bhat\b|\bhaat\b|hatkhola|market|হাট|বাজার|মার্কেট', re.I)
bz = json.load(open(G + 'bd-bazars.geojson'))
for f in bz['features']:
    p = f['properties']
    if p.get('district') != 'Natore':
        continue
    raw = p.get('name') or ''
    if not MKT.search(raw):
        continue
    lng, lat = f['geometry']['coordinates'][:2]
    u = upazila_of(lat, lng, BY_NAME.get(p.get('upazila')))
    if u is None:
        continue
    first = raw.split(',')[0].strip()
    bn = ' '.join(w for w in first.split() if BN.search(w)) or None
    en = ' '.join(w for w in first.split() if not BN.search(w)) or None
    rows.append((u, 'market', en or bn, bn, bn is not None, lat, lng, 'osm', p.get('osm_id')))

unions = json.load(open(B + 'unions.json'))
for uid in map(str, UPZ):
    for x in unions.get(uid, []):
        # place the union on a village of the same name in that upazila when there is one
        m = [r for r in rows if r[0] == int(uid) and r[1] == 'village' and r[2].lower() == x['name'].lower()]
        lat, lng = (m[0][5], m[0][6]) if m else (None, None)
        rows.append((int(uid), 'union', x['name'], x['bn_name'], True, lat, lng, 'bbs', 'union:' + x['id']))

print('-- =====================================================================')
print('--  রুটের জন্য এলাকার নাম: নাটোর জেলার উপজেলা, গ্রাম, বাজার ও ইউনিয়ন (generated by scripts/route-places/build.py).')
print('--  * geo_upazilas: the 7 upazilas with their boundary (geoBoundaries 2020; Naldanga has none there, it was part of Natore Sadar).')
print('--  * route_places: villages (GeoNames, CC BY 4.0; Bangla names were machine-made: bn_checked = false until someone fixes them),')
print('--    markets (© OpenStreetMap contributors, ODbL), unions (official names). Reference data: every signed-in person may read it;')
print('--    people with ops.route_setting.edit (anywhere) may fix a spelling, add a place or hide a wrong one, through functions only.')
print('--  * route_save is NOT replaced: a stop made from a place is an ordinary stop with that name and location.')
print('-- =====================================================================')
print(open(sys.argv[2]).read() if len(sys.argv) > 2 else '')
print('insert into public.geo_upazilas (code, district, district_bn, name, name_bn, boundary) values')
vals = []
for code, (en, bn) in UPZ.items():
    ring = polys.get(code)
    b = 'null' if ring is None else q(json.dumps([[round(y, 5), round(x, 5)] for x, y in ring], separators=(',', ':'))) + '::jsonb'
    vals.append(f"  ({code}, 'Natore', 'নাটোর', {q(en)}, {q(bn)}, {b})")
print(',\n'.join(vals) + '\non conflict (code) do nothing;\n')
print('insert into public.route_places (upazila_code, kind, name, name_bn, bn_checked, lat, lng, source, source_ref) values')
print(',\n'.join(f'  ({r[0]}, {q(r[1])}, {q(r[2])}, {q(r[3])}, {"true" if r[4] else "false"}, {num(r[5])}, {num(r[6])}, {q(r[7])}, {q(r[8])})' for r in rows))
print('on conflict (source, source_ref) do nothing;')
cnt = {}
for r in rows:
    cnt[(r[0], r[1])] = cnt.get((r[0], r[1]), 0) + 1
print('-- counts: ' + ', '.join(f'{UPZ[u][0]} {k} {n}' for (u, k), n in sorted(cnt.items())), file=sys.stderr)
